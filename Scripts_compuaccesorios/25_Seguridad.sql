
-- SEGURIDAD

-- Crear Roles
CREATE ROLE rol_administrador;
CREATE ROLE rol_vendedor;
CREATE ROLE rol_tecnico;
CREATE ROLE rol_gerente;

-- Quitar a PUBLIC la ejecucion por defecto de las funciones de los actores
REVOKE ALL ON ALL FUNCTIONS IN SCHEMA SV_ADMINISTRADOR FROM PUBLIC;
REVOKE ALL ON ALL FUNCTIONS IN SCHEMA SV_VENDEDOR FROM PUBLIC;
REVOKE ALL ON ALL FUNCTIONS IN SCHEMA SV_TECNICO FROM PUBLIC;
REVOKE ALL ON ALL FUNCTIONS IN SCHEMA SV_GERENTE FROM PUBLIC;

-- Otorgar uso de esquemas a los roles
GRANT USAGE ON SCHEMA SV_ADMINISTRADOR TO rol_administrador;
GRANT USAGE ON SCHEMA SV_VENDEDOR TO rol_vendedor;
GRANT USAGE ON SCHEMA SV_TECNICO TO rol_tecnico;
GRANT USAGE ON SCHEMA SV_GERENTE TO rol_gerente;

-- Otorgar ejecucion de funciones a los roles
GRANT EXECUTE ON ALL FUNCTIONS IN SCHEMA SV_ADMINISTRADOR TO rol_administrador;
GRANT EXECUTE ON ALL FUNCTIONS IN SCHEMA SV_VENDEDOR TO rol_vendedor;
GRANT EXECUTE ON ALL FUNCTIONS IN SCHEMA SV_TECNICO TO rol_tecnico;
GRANT EXECUTE ON ALL FUNCTIONS IN SCHEMA SV_GERENTE TO rol_gerente;